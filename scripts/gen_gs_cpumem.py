"""Generate rtl/gs_cpumem.sv from Arcade-Vamphalf_MiSTer's rtl/vh_cpumem.sv.

    python scripts/gen_gs_cpumem.py [COMMIT]      default: the commit scripts/vendor.json names

Applies this board's decode, cached-space layout and video/register ports as exact text substitutions,
each asserted to match once, so the caches, write buffer, prefetch and port-2 logic stay Vamphalf's text.
Also Arcade-Eolith_MiSTer's latch of an accepted store for its cache update (wl_*, gen_eo_cpumem.py): e1_pipe
holds bus_* through S_WLOOK only for Vamphalf's cached regions, which X2222's RAM at 0x40000000 is mostly not.
When an assertion fails after an upstream change, edit the substitution here, not the output; then set
rtl/gs_cpumem.sv's commit in scripts/vendor.json.
"""
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from mame_capture import load_env  # noqa: E402

VAMPHALF = Path(load_env().get("MISTER_CORES_ROOT") or REPO.parent) / "Arcade-Vamphalf_MiSTer"
man = json.loads((REPO / "scripts" / "vendor.json").read_text(encoding="utf-8"))
pinned = next((f["commit"] for f in man["files"] if f["path"] == "rtl/gs_cpumem.sv"), "HEAD")
COMMIT = sys.argv[1] if len(sys.argv) > 1 else pinned
s = subprocess.run(["git", "-C", str(VAMPHALF), "show", f"{COMMIT}:rtl/vh_cpumem.sv"],
                   capture_output=True, check=True).stdout.decode()


def rep(a, b, count=1):
    global s
    n = s.count(a)
    assert n == count, (n, a[:100])
    s = s.replace(a, b)


def between(start, end):
    i = s.index(start)
    return s[i:s.index(end, i)]


rep(s[:s.index("module vh_cpumem")], """// SPDX-License-Identifier: GPL-3.0-or-later
// The E1's memory system: address decode, the CPU's internal RAM, the caches in front of work RAM and the
// ROMs (in SDRAM), the VRAM, palette, backup RAM and scroll-register ports, the I/O port, and the owner of
// sdram.sv's port 2. Generated by scripts/gen_gs_cpumem.py from Arcade-Vamphalf_MiSTer rtl/vh_cpumem.sv: the
// decode and the ports are this board's; the caches, write buffer, prefetch and port-2 logic are Vamphalf's.
//
// Program space (gstream.cpp gstream_32bit_map 272-287, x2222_32bit_map 366-383; e132xs.cpp iram_8k_map):
//   0x00000000-0x003fffff  work RAM, 4 MB       SDRAM WRAM_BASE, through the caches
//   0x40000000-0x403fffff  X2222: RAM, 4 MB     SDRAM XRAM_BASE, through the caches
//   0x4e000000-0x4e1fffff  gstream: data ROM    SDRAM DATA_BASE, through the caches; writes are dropped
//   0x4f400000-0x4f406fff  gstream: palette     pal_*
//   0x4f000000-0x4ff00003  scroll registers     scr_* (by bits 23:20, write only; the top decodes them per map)
//   0x80000000-0x80003fff  VRAM, 16 KB          spr_*
//   0xc0000000-0xdfffffff  internal RAM, 8 KB mirrored
//   0xffc00000-0xffc01fff  backup RAM, 8 KB     x_*
//   0xfff80000-0xffffffff  gstream: boot ROM    SDRAM ROM_BASE + 0x80000, through the caches
//   0xfff00000-0xffffffff  X2222: boot ROM      SDRAM ROM_BASE, through the caches
//   anything else reads 0, writes are dropped
//
// Caches: I 16 KB, D 4 KB, direct-mapped, 16-byte lines filled by one double read. Instruction fetches
// have their own port (if_*, 8 bytes) so fetch-ahead does not wait behind loads and stores. Stores to
// work RAM and X2222's RAM are written through: they update whichever cache holds the line and enter a
// four-entry write buffer (wq_*), each entry written as one burst. A miss waits for the buffer only while it
// holds a store to the missed line; otherwise its fill goes to SDRAM before the buffer.
// After every D-cache fill the next line is read into a 16-byte prefetch buffer when port 2 is idle; a D
// miss on that line fills from it in two clocks, waiting for it if it is on its way (S_PFW). A store to the
// buffered line, or to the line in flight (including in the clock it arrives), discards it. Port 2 serves
// the write buffer before the prefetch, so the prefetch never holds data older than a store.
//
// CPU bus timing (req held until ack): a write is acked in its request clock, combinationally: one that
// takes effect in that clock (I/O, internal RAM, VRAM, palette, backup RAM, scroll), or a store the write
// buffer can take, whose cache update follows in S_WLOOK from the address, lanes and data registered in
// the request clock (wl_*). Reads of I/O and internal/video RAM ack from a register one clock after the
// request; a cache hit (S_LOOK) and a data fill (S_FILL2) ack combinationally. A read the CPU announced on
// la_* in the clock before its request, while the D-cache was free, was looked up then: a hit acks in the
// request clock.
// Instruction port: if_addr is looked up in every clock in which the data side, a fill or the sweep does
// not hold the RAM it needs (i_free); if_ack comes in the clock after a lookup of the address still
// requested, so a lookup of an address the CPU has since changed is dropped. An I-cache miss is filled by
// the data side's miss logic when that has no request. Fetches outside the cached ranges and the internal
// RAM read 0. A store updates the I-cache in S_WLOOK, the clock it is acked in; the CPU drops any fetched
// 8 bytes the store hits, and every later lookup reads the new data.
//
// SDRAM port 2 (sdram.sv's toggle protocol, burst writes), in priority order: download writes (dl_*), line
// fills, the write buffer, the prefetch. It is reset only by prst (the PLL's lock), never by the core
// reset: MiSTer holds the core reset for the whole download (LESSONS_LEARNED, "Never hold the memory path
// in the core reset").
// SDRAM words hold the even byte in [7:0]; the CPU is big-endian, so data is byte-swapped at this seam.

""")

rep(between("module vh_cpumem #(", "\t// CPU\n"), """module gs_cpumem #(
	parameter [26:0] ROM_BASE  = 27'h0000000,
	parameter [26:0] WRAM_BASE = 27'h0800000,
	parameter [26:0] DATA_BASE = 27'h0100000,
	parameter [26:0] XRAM_BASE = 27'h0c00000
) (
	input             clk,
	input             prst,            // power-up only: the port-2 side
	input             rst,
	input             x2,              // X2222's map (x2222_32bit_map); 0: gstream_32bit_map
	input             pal_wait,        // a write to the pal_* window waits (not acked, not written) while set

""")
rep(between("\t// video RAMs (vh_video)", "\t// I/O: one-clock pulses"), """	// VRAM and palette (gs_video): registered reads, data one clock after the address
	output            spr_we,
	output     [3:0]  spr_be,
	output     [11:0] spr_addr,
	output     [31:0] spr_wd,
	input      [31:0] spr_rd,
	output            pal_we,
	output     [3:0]  pal_be,
	output     [12:0] pal_addr,
	output     [31:0] pal_wd,
	input      [31:0] pal_rd,
	// the backup RAM at 0xffc00000 (registered read, as the video RAMs)
	output            x_we,
	output     [3:0]  x_be,
	output     [10:0] x_addr,
	output     [31:0] x_wd,
	input      [31:0] x_rd,
	// the scroll registers: a write to 0x4fN00000-0x4fN00003, N = scr_sel (bits 23:20)
	output            scr_we,
	output     [3:0]  scr_sel,
	output     [31:0] scr_wd,

""")
rep("""	output     [23:4] dbg_miss_line,
	output            xflip_we         // a write to 0xe000xxxx (jmpbreak_flipscreen_w): bus_wdata, bus_be
);""", """	output     [23:4] dbg_miss_line
);""")

rep(between("// ---------------------------------------------------------------- decode", "// SDRAM granule"),
    """// ---------------------------------------------------------------- decode
// boot ROM: 0xfff80000-0xffffffff on gstream (512 KB), 0xfff00000-0xffffffff on X2222 (1 MB)
function rom_at(input [31:0] a);
	rom_at = x2 ? a[31:20] == 12'hfff : a[31:19] == 13'h1fff;
endfunction
// the third cached range: gstream's data ROM (0x4e000000, 2 MB) or X2222's RAM (0x40000000, 4 MB)
function hi_at(input [31:0] a);
	hi_at = x2 ? a[31:22] == 10'h100 : a[31:21] == 11'h270;
endfunction
function [23:0] ca_of(input w, input r, input [31:0] a);
	ca_of = w ? {2'b00, a[21:0]} : r ? {4'b0100, a[19:0]} : {2'b10, a[21:0]};
endfunction
wire r_wram = bus_addr[31:22] == 10'd0;
wire r_rom  = rom_at(bus_addr);
wire r_iram = bus_addr[31:29] == 3'b110;
wire r_spr  = bus_addr[31:14] == 18'h20000;            // VRAM
wire r_hi   = hi_at(bus_addr);
wire r_sprh = r_hi && x2;                // written through the caches (Vamphalf's name); the data ROM drops writes
wire r_pal  = !x2 && bus_addr[31:15] == 17'h09e80 && bus_addr[14:12] != 3'b111;   // 0x4f400000-0x4f406fff
wire r_x    = bus_addr[31:13] == 19'h7fe00;            // 0xffc00000-0xffc01fff
wire r_scr  = bus_addr[31:24] == 8'h4f && bus_addr[19:2] == 18'd0 && !r_pal;
wire r_sd   = r_wram || r_rom || r_hi;    // through the caches
wire [23:0] caddr = ca_of(r_wram, r_rom, bus_addr);
wire        la_wram = la_addr[31:22] == 10'd0;
wire        la_rom  = rom_at(la_addr);
wire        la_hi   = hi_at(la_addr);
wire [23:0] la_ca   = ca_of(la_wram, la_rom, la_addr);

wire [31:0] ifa    = {if_addr, 3'b000};
wire        i_wram = ifa[31:22] == 10'd0;
wire        i_rom  = rom_at(ifa);
wire        i_iram = ifa[31:29] == 3'b110;
wire        i_sd   = i_wram || i_rom || hi_at(ifa);
wire [23:0] i_caddr = ca_of(i_wram, i_rom, ifa);

// the cached space: 0x000000 work RAM, 0x400000 the boot ROM's 1 MB window, 0x800000 the data ROM or X2222's RAM
function [26:0] sdram_of(input [23:0] ca);
	sdram_of = ca[23] ? (x2 ? XRAM_BASE + {5'd0, ca[21:0]} : DATA_BASE + {6'd0, ca[20:0]}) :
	           !ca[22] ? WRAM_BASE + {5'd0, ca[21:0]} : ROM_BASE + {7'd0, ca[19:0]};
endfunction

""")

# Eolith's latch of the accepted store, for the cache update in S_WLOOK
rep("wire [7:0]  st_be8 = bus_addr[2] ? {4'b0, bus_be} : {bus_be, 4'b0};",
    """wire [7:0]  st_be8 = bus_addr[2] ? {4'b0, bus_be} : {bus_be, 4'b0};
// the store as accepted, for its cache update in S_WLOOK (bus_* may be the next access by then)
reg  [23:0] wl_ca;
reg  [7:0]  wl_be;
reg  [31:0] wl_d;
always @(posedge clk) if (idle_go && bus_wr) begin
	wl_ca <= caddr;
	wl_be <= st_be8;
	wl_d  <= bus_wdata;
end""")
rep("\t.la(ic_by_d ? caddr : i_caddr), .hit(ic_hit), .q(ic_q),",
    "\t.la(st == S_WLOOK ? wl_ca : ic_by_d ? caddr : i_caddr), .hit(ic_hit), .q(ic_q),")
rep("\t.la(la_take ? la_ca : caddr), .hit(dc_hit), .q(dc_q),",
    "\t.la(st == S_WLOOK ? wl_ca : la_take ? la_ca : caddr), .hit(dc_hit), .q(dc_q),")
rep("\t.st_we(st == S_WLOOK && ic_hit), .st_be(st_be8), .st_d({bus_wdata, bus_wdata}));",
    "\t.st_we(st == S_WLOOK && ic_hit), .st_be(wl_be), .st_d({wl_d, wl_d}));")
rep("\t.st_we(st == S_WLOOK && dc_hit), .st_be(st_be8), .st_d({bus_wdata, bus_wdata}));",
    "\t.st_we(st == S_WLOOK && dc_hit), .st_be(wl_be), .st_d({wl_d, wl_d}));")

rep(between("// 8 bytes wide for the instruction port;", "vh_cache_ram #(.AW(10)"),
    """// 8 bytes wide for the instruction port; the data side has it in its request clock. 8 KB, mirrored.
wire [63:0] iram_q;
wire        ir_by_d = idle_go && !bus_io && r_iram;
wire [12:3] ir_da = bus_addr[12:3], ir_ia = if_addr[12:3];
""")

rep(between("assign spr_we   =", "assign io_rd    ="), """assign spr_we   = idle_go && bus_wr && !bus_io && r_spr;
assign spr_be   = bus_be;
assign spr_addr = bus_addr[13:2];
assign spr_wd   = bus_wdata;
assign pal_we   = idle_go && bus_wr && !bus_io && r_pal && !pal_wait;
assign pal_be   = bus_be;
assign pal_addr = bus_addr[14:2];
assign pal_wd   = bus_wdata;
assign x_we     = idle_go && bus_wr && !bus_io && r_x;
assign x_be     = bus_be;
assign x_addr   = bus_addr[12:2];
assign x_wd     = bus_wdata;
assign scr_we   = idle_go && bus_wr && !bus_io && r_scr;
assign scr_sel  = bus_addr[23:20];
assign scr_wd   = bus_wdata;
""")
rep("wire        w_fast  = idle_go && bus_wr && (bus_io || r_iram || r_spr || r_pal && !pal_wait || r_x);",
    "wire        w_fast  = idle_go && bus_wr && (bus_io || r_iram || r_spr || r_pal && !pal_wait || r_x || r_scr);")
rep("""			end else if (r_inp) begin
				rdata_r <= bus_addr[17] ? aoh_p12 : aoh_sys;
				ack_r <= 1'b1; st <= S_ACK;
			end else if (r_iram || r_spr || r_pal || r_x) begin""",
    """			end else if (r_iram || r_spr || r_pal || r_x || r_scr && bus_wr) begin""")

for tok in ["aoh", "prg2", "lm_", "lm ", "lm)", "xflip", "PRGLO", "SPRHI", "r_inp", "ir8k"]:
    left = [ln for ln in s.splitlines() if tok in ln]
    assert not left, (tok, left[:3])
(REPO / "rtl" / "gs_cpumem.sv").write_text(s, encoding="utf-8", newline="\n")
print(f"rtl/gs_cpumem.sv from vh_cpumem.sv at {COMMIT}: {len(s.splitlines())} lines")
